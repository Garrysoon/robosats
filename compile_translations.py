def compile_all():
    print("=" * 65)
    print("  🌐 RoboSats Multi-Language Translation Compiler")
    print("=" * 65)

    for lang_code, (lang_name, po_code) in LANGUAGES_INFO.items():
        locale_dir = BASE_DIR / "locale" / lang_code / "LC_MESSAGES"
        locale_dir.mkdir(parents=True, exist_ok=True)

        po_path = locale_dir / "django.po"
        mo_path = locale_dir / "django.mo"

        po = polib.POFile()
        po.metadata = {
            'Project-Id-Version': 'RoboSats Coordinator 0.9.15',
            'Report-Msgid-Bugs-To': '',
            'POT-Creation-Date': '2026-11-24 00:00+0000',
            'PO-Revision-Date': '2026-11-24 00:00+0000',
            'Last-Translator': 'Antigravity Localization Engine <admin@robosats.local>',
            'Language-Team': f'{lang_name} <{po_code}@li.org>',
            'Language': po_code,
            'MIME-Version': '1.0',
            'Content-Type': 'text/plain; charset=UTF-8',
            'Content-Transfer-Encoding': '8bit',
        }

        count = 0
        for msgid, translations in ALL_TRANSLATIONS.items():
            translated = translations.get(lang_code)
            if not translated:
                # Fallback to English or Russian
                translated = translations.get("ru", msgid)
            entry = polib.POEntry(msgid=msgid, msgstr=translated)
            po.append(entry)
            count += 1

        po.save(str(po_path))
        po.save_as_mofile(str(mo_path))
        print(f"[{lang_code}] {lang_name}: {count} строк -> {mo_path}")

